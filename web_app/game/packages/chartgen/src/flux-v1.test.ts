  it("computeLaneSeed takes the first 4 digest bytes as a big-endian uint32", async () => {
    const canonical = laneSeedInput(AUDIO_HASH, HASH_OPTIONS);
    const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(canonical)));
    const expected = ((digest[0]! << 24) | (digest[1]! << 16) | (digest[2]! << 8) | digest[3]!) >>> 0;
    await expect(computeLaneSeed(AUDIO_HASH, HASH_OPTIONS)).resolves.toBe(expected);
  });

  it("mulberry32 is deterministic, in [0,1), and seed-sensitive", () => {
    const a = mulberry32(123456);
    const b = mulberry32(123456);
    for (let i = 0; i < 32; i++) {
      const x = a();
      expect(x).toBe(b());
      expect(x).toBeGreaterThanOrEqual(0);
      expect(x).toBeLessThan(1);
    }
    expect(mulberry32(1)()).not.toBe(mulberry32(2)());
  });

  it("selectDensity caps every rolling 1 s window and prefers high confidence", () => {
    const crowded = Array.from({ length: 40 }, (_, i) => ({ tMs: i * 100, confidence: 0.5 }));
    const kept = selectDensity(crowded, 7);
    for (const o of kept) {
      expect(kept.filter((k) => k.tMs >= o.tMs && k.tMs < o.tMs + 1000).length).toBeLessThanOrEqual(7);
    }
    const mixed = [
      ...Array.from({ length: 7 }, (_, i) => ({ tMs: i * 40, confidence: 0.9 })),
      ...Array.from({ length: 13 }, (_, i) => ({ tMs: 400 + i * 40, confidence: 0.1 })),
    ];
    const high = selectDensity(mixed, 7);
    expect(high).toHaveLength(7);
    for (const o of high) expect(o.confidence).toBeCloseTo(0.9, 10);
  });

  it("assignLanes on synthetic onsets: deterministic, jack-capped, chord-capped", () => {
    const onsets = Array.from({ length: 200 }, (_, i) => ({ tMs: i * 100, confidence: 0.5 }));
    const run = () => assignLanes(onsets, mulberry32(777), { chordProbability: 0.3 });
    const a = run();
    expect(a).toEqual(run());
    const byTime = new Map<number, typeof a>();
    for (const n of a) {
      const g = byTime.get(n.t) ?? [];
      g.push(n);
      byTime.set(n.t, g);
    }
    for (const g of byTime.values()) {
      if (g.length === 2) expect(Math.abs(g[0]!.lane - g[1]!.lane)).toBeGreaterThanOrEqual(2);
      expect(g.length).toBeLessThanOrEqual(2);
    }
  });
