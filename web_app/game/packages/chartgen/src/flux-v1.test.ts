    //
    // R13/R19: the real reference (`models/spike/testvectors/baseline_onsets.json`) is
    // generated by `models/spike/baseline_flux.py` on the operator's pinned Python env,
    // which does NOT exist on this machine — so the row is SKIPPED here and prints the
