/**
 * Minimal RIFF walker: find `fmt ` + `data` chunks (never assume a 44-byte
 * header). 22050 Hz mono 16-bit → Float32Array in [-1, 1). Mirrors the helper
 * in `mel.test.ts` — the parity row reads the same spike vector.
 */
function decodeWavMono(buf: Uint8Array): Float32Array {
  const ascii = (start: number, end: number): string =>
    new TextDecoder("ascii").decode(buf.subarray(start, end));
  const view = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  if (ascii(0, 4) !== "RIFF" || ascii(8, 12) !== "WAVE") throw new Error("not a RIFF/WAVE file");
  let pos = 12;
  let fmt: { channels: number; sampleRate: number; bits: number } | null = null;
  let data: Uint8Array | null = null;
  while (pos + 8 <= buf.length) {
    const id = ascii(pos, pos + 4);
    const size = view.getUint32(pos + 4, true);
    const body = buf.subarray(pos + 8, pos + 8 + size);
    if (id === "fmt ") {
      fmt = {
        channels: view.getUint16(pos + 10, true),
        sampleRate: view.getUint32(pos + 12, true),
        bits: view.getUint16(pos + 22, true),
      };
    } else if (id === "data") {
      data = new Uint8Array(body);
    }
    pos += 8 + size + (size % 2);
  }
  if (!fmt || !data) throw new Error("missing fmt/data chunk");
  if (fmt.sampleRate !== SR) throw new Error(`wav sampleRate ${fmt.sampleRate} != pinned ${SR}`);
  if (fmt.channels !== 1) throw new Error(`wav channels ${fmt.channels} != 1`);
  if (fmt.bits !== 16) throw new Error(`wav bits ${fmt.bits} != 16`);
  const n = data.length / 2;
  const out = new Float32Array(n);
  const dv = new DataView(data.buffer, data.byteOffset, data.byteLength);
  for (let i = 0; i < n; i++) out[i] = dv.getInt16(i * 2, true) / 32768;
  return out;
}

/**
 * Seeded, deterministic kick-grid PCM: a kick every beat plus a melody line.
 * Kick times are returned so the onset row can assert against known truth.
 */
function beatGrid(
  seconds: number,
  bpm = 120,
  opts: { offbeats?: boolean; seed?: number } = {},
): { mono: Float32Array; timesMs: number[] } {
  const rng = mulberry32(opts.seed ?? 7);
  const n = Math.round(seconds * SR);
  const out = new Float32Array(n);
  const beatMs = 60_000 / bpm;
  const timesMs: number[] = [];
  const addKick = (atMs: number, amp: number): void => {
    const s0 = Math.round((atMs / 1000) * SR);
    const len = Math.min(Math.round(0.12 * SR), n - s0);
    for (let i = 0; i < len; i++) {
      const t = i / SR;
      const f = 55 + 35 * Math.exp(-t * 25); // pitch drop = a sharp magnitude jump
      out[s0 + i]! += Math.sin(2 * Math.PI * f * t) * Math.exp(-t * 14) * amp;
    }
  };
  for (let t = 0; t < seconds * 1000; t += beatMs) {
    addKick(t, 0.55);
    timesMs.push(t);
    if (opts.offbeats) {
      addKick(t + beatMs / 2, 0.3);
      timesMs.push(t + beatMs / 2);
    }
  }
  const tone = 440 + 55 * Math.floor(rng() * 4);
  for (let i = 0; i < n; i++) {
    const phase = (i / SR) % 0.25;
    out[i]! += 0.06 * Math.exp(-phase * 18) * Math.sin((2 * Math.PI * tone * i) / SR);
  }
  return { mono: out, timesMs: timesMs.sort((a, b) => a - b) };
}

function resolved(opts: Partial<ResolvedGenerateOptions> = {}): ResolvedGenerateOptions {
  return { audioHash: AUDIO_HASH, targetNps: 7, density: 0, seed: 12345, ...opts };
}

function candidate(mono: Float32Array, opts: Partial<ResolvedGenerateOptions> = {}): Beatmap {
  const ms = Math.max(1, Math.round((mono.length * 1000) / SR));
  return generateCandidate(mono, { sampleRate: SR, durationMs: ms }, resolved(opts)).chart;
}

